# 条件类：问某条规则是否适用（「支持7天无理由退货吗」「可以退货吗」「是否允许换货」）。
# 与「我要退货」这类诉求的区别是：句末是疑问（吗/么/嘛）且句中没有任何办理动作措辞。
# 只靠 POLICY_QUERY_HINTS 的词表覆盖不到这种句式（"支持7天无理由退货吗"里没有"支持吗"），
# 实测它会被判成 return，直接回「好的，我来帮您办理退货」——答非所问。
CONDITION_FORM = r"(支持|能|可以|是否|允许|属于|算)[^。？！]{0,24}(吗|么|嘛)[？?]?[。.!！]?$"

# 评价类：问办理体验（难易/繁琐），如「退货麻烦吗」「退款麻不麻烦」「退货难不难」。
# 这类句子既没有政策词汇，也没有条件类的判断动词（支持/能/可以…），
# 此前会被判成 return 直接进办理流，回「好的，我来帮您办理退货 / 请补充订单号」——答非所问。
_EVALUATIVE_WORD = r"(?:麻烦|方便|复杂|困难|容易|简单|繁琐|费事|好办|好退|好换|难)"
EVALUATIVE_FORM = (
    # ① 评价词 + 句末疑问：「退货麻烦吗」「退款方便吗」
    _EVALUATIVE_WORD + r"[吗么嘛呢]"
    # ② A不A 重叠式：「退货麻烦不麻烦」「退款难不难」
    + r"|" + _EVALUATIVE_WORD + r"不" + _EVALUATIVE_WORD
    # ③ 缩略重叠式（麻+不麻烦）：「退款麻不麻烦」「退个货方不方便」，限句末避免误伤陈述句
    + r"|" + r"不" + _EVALUATIVE_WORD + r"(?:[吗么嘛呢]|[？?]|$)"
)

# 疑问句式：整句在问「规则是什么 / 怎么办 / 怎么退 / 哪天算起 / 什么状态才能退」。
# 这类句子既没有政策词表命中，也不含条件类判断动词，前两道守卫都覆盖不到，
# 实测会被判成 return/refund 直接进办理流（回「还需要您补充订单号」）——答非所问。
# 补的正是真实客服里最高频的几句：
#   「7天无理由的7天是从哪天开始算的」「商品有质量问题怎么退货」
#   「退货商品要保持什么状态才能退」「商家一直不退款怎么办」
#   「包邮商品退货，原来的运费退吗」
# 关键：不能用裸「怎么」。既有用例「退款进度怎么样了」是查进度（refund），
# 「怎么样」必须放行，所以只匹配「怎么 + 具体动作字」与句末「退/换…吗」。
QUESTION_FORM = (
    r"怎么(?:退|换|办|弄|处理|申请|操作|回事)"
    r"|如何(?:退|换|办|申请|操作|处理)"
    r"|哪天|几时|何时"
    r"|才能"
    r"|要不要|需不需要"
    r"|(?:退还|退回|退款|退货|换货|运费|邮费|退|换)[吗么嘛呢]$"
)

# 三个句式分支合并成一个正则：一次 search 取代三次 search，
# 判定结果与「三个正则分别 search 再取或」完全等价（分支互斥，$ 锚点各自保留）。
POLICY_QUESTION_RE = re.compile(
    "(?:" + CONDITION_FORM + ")|(?:" + EVALUATIVE_FORM + ")|(?:" + QUESTION_FORM + ")"
)